"""Generates lib/domain/library/text_normalisation_table.g.dart.

The table holds the Unicode NFKD decomposition of every code point, in all
planes, for which unicodedata.normalize('NFKD', c) differs from c. Hangul
syllables (U+AC00 to U+D7A3) are left out: the Dart code decomposes them with
the standard algorithm. The file also holds the ranges of general category Mn
inside the combining-diacritic blocks (below), which the Dart code removes
after decomposition, and the single-code-point lower-case map of Python's
str.lower(), which the Dart code applies per code point. Marks of other
scripts (Devanagari, Thai, Hebrew, Arabic and so on) are kept.

Run from app/ with isolated mode (no user site, no cwd imports):

    python3 -I tool/gen_text_normalisation_table.py

Output is deterministic for one Unicode version (printed in the header).
Run `dart format` on the result. No third-party package is used.
"""

import sys
import unicodedata

HANGUL = (0xAC00, 0xD7A3)
# Combining-diacritic blocks: combining diacritical marks, extended,
# supplement, for symbols, and half marks.
DIACRITIC_BLOCKS = [
    (0x0300, 0x036F),
    (0x1AB0, 0x1AFF),
    (0x1DC0, 0x1DFF),
    (0x20D0, 0x20FF),
    (0xFE20, 0xFE2F),
]
OUT = "lib/domain/library/text_normalisation_table.g.dart"


def dart_string(text):
    parts = []
    for ch in text:
        if ch.isascii() and ch.isalnum():
            parts.append(ch)
        else:
            parts.append("\\u{%X}" % ord(ch))
    return "'" + "".join(parts) + "'"


def mn_ranges():
    ranges = []
    for cp in range(0x110000):
        in_block = any(lo <= cp <= hi for lo, hi in DIACRITIC_BLOCKS)
        if in_block and unicodedata.category(chr(cp)) == "Mn":
            if ranges and ranges[-1][1] == cp - 1:
                ranges[-1][1] = cp
            else:
                ranges.append([cp, cp])
    return ranges


def main():
    lines = []
    count = 0
    for cp in range(0x110000):
        if HANGUL[0] <= cp <= HANGUL[1]:
            continue
        ch = chr(cp)
        d = unicodedata.normalize("NFKD", ch)
        if d == ch:
            continue
        lines.append("  0x%04X: %s," % (cp, dart_string(d)))
        count += 1
    ranges = mn_ranges()
    lowers = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        low = chr(cp).lower()
        if len(low) == 1 and low != chr(cp):
            lowers.append("  0x%04X: 0x%04X," % (cp, ord(low)))
    flat = ", ".join("0x%04X, 0x%04X" % (lo, hi) for lo, hi in ranges)
    header = """// GENERATED FILE. DO NOT EDIT.
//
// Generated by tool/gen_text_normalisation_table.py with
// unicodedata.normalize('NFKD', ...), Unicode %s, Python %s.
// Regenerate with: python3 -I tool/gen_text_normalisation_table.py
// %d decomposition entries (all planes, Hangul syllables excluded),
// %d combining-diacritic mark ranges and %d lower-case entries.
// A code point without a decomposition entry stays as it is (for example
// U+0127 and U+0131).
library;

/// Unicode version of the data below.
const String nfkdUnicodeVersion = '%s';

/// Number of entries in [nfkdDecomposition].
const int nfkdEntryCount = %d;

/// General category Mn inside the combining-diacritic blocks (U+0300 to
/// U+036F, U+1AB0 to U+1AFF, U+1DC0 to U+1DFF, U+20D0 to U+20FF and U+FE20 to
/// U+FE2F), as sorted, inclusive (low, high) pairs, flattened.
const List<int> diacriticMarkRanges = [%s];

/// Single-code-point lower-case mapping of Python's str.lower(), by code
/// point. Multi-code-point lower cases are not in the map.
const Map<int, int> lowerCaseMap = {
%s
};

/// NFKD decomposition (including combining marks) by code point.
const Map<int, String> nfkdDecomposition = {
""" % (
        unicodedata.unidata_version,
        "%d.%d" % sys.version_info[:2],
        count,
        len(ranges),
        len(lowers),
        unicodedata.unidata_version,
        count,
        flat,
        "\n".join(lowers),
    )
    with open(OUT, "w", encoding="ascii") as f:
        f.write(header + "\n".join(lines) + "\n};\n")
    print("wrote", OUT, count, "entries,", len(ranges), "mark ranges,", len(lowers), "lower-case entries")


main()
