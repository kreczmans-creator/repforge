#!/usr/bin/env python3
"""Mirror implementation-handoff review state into GitHub issues.

One issue per handoff (label `ai-review`). The script only mirrors what the
handoff and review files record; it never claims a review happened.
Stdlib only, Python 3.10+.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

LABEL = "ai-review"
LABEL_COLOR = "0e8a16"
LABEL_DESC = "AI coordination: independent review tracking"
CLOSING = {"SUPERSEDED": "not_planned", "ACCEPTED_BY_OWNER": "completed"}
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
MARKER_RE = re.compile(
    r"^<!-- coordination: (HO-\d+) status=(\S*) reviews=(\S*) commit=(\S*) -->")
TITLE_RE = re.compile(r"^\[AI review\] (HO-\d+)\b")
HANDOFFS = "docs/ai-coordination/handoffs"
REVIEWS = "docs/ai-coordination/reviews"


class ApiError(Exception):
    def __init__(self, status: int, message: str):
        super().__init__(f"GitHub API error {status}: {message}")
        self.status = status
        self.message = message


class GitHubApi:
    def __init__(self, token: str, base: str = "https://api.github.com"):
        self.token = token
        self.base = base.rstrip("/")

    def _request(self, method: str, path: str, data=None):
        body = None if data is None else json.dumps(data).encode()
        req = urllib.request.Request(self.base + path, data=body, method=method)
        req.add_header("Authorization", f"Bearer {self.token}")
        req.add_header("Accept", "application/vnd.github+json")
        req.add_header("X-GitHub-Api-Version", "2022-11-28")
        req.add_header("User-Agent", "repforge-coordination")
        if body is not None:
            req.add_header("Content-Type", "application/json")
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                raw = resp.read()
        except urllib.error.HTTPError as e:
            raw = e.read().decode("utf-8", "replace")
            try:
                msg = json.loads(raw)
                text = msg.get("message", raw)
                if msg.get("errors"):
                    text += " " + json.dumps(msg["errors"])
            except ValueError:
                text = raw
            raise ApiError(e.code, text) from None
        except urllib.error.URLError as e:
            raise ApiError(0, str(e.reason)) from None
        return json.loads(raw) if raw else None

    def get(self, path):
        return self._request("GET", path)

    def post(self, path, data):
        return self._request("POST", path, data)

    def patch(self, path, data):
        return self._request("PATCH", path, data)


def _strip(v: str) -> str:
    return v.strip().strip("`").strip()


def parse_meta(text: str):
    lines = text.splitlines()
    title_line = lines[0] if lines else ""
    meta: dict[str, str] = {}
    for line in lines[1:]:
        if line.startswith("## "):
            break
        m = re.match(r"^- ([A-Za-z][A-Za-z ]*?):\s*(.*)$", line)
        if m:
            meta[m.group(1).strip()] = m.group(2).strip()
    return title_line, meta


def load_reviews(root: Path):
    out = {}
    d = root / REVIEWS
    if d.is_dir():
        for p in sorted(d.glob("RV-*.md")):
            _, meta = parse_meta(p.read_text(encoding="utf-8"))
            out[p.stem] = {
                "outcome": _strip(meta.get("Outcome", "")) or "unknown",
                "commit": _strip(meta.get("Commit reviewed", "")),
                "date": _strip(meta.get("Date", "")) or "undated",
            }
    return out


def load_handoffs(root: Path, reviews: dict):
    result = []
    d = root / HANDOFFS
    if not d.is_dir():
        return result
    for p in sorted(d.glob("HO-*.md")):
        title_line, meta = parse_meta(p.read_text(encoding="utf-8"))
        m = re.match(r"^#\s+(HO-\d+)\s+[—-]+\s*(.*)$", title_line)
        if not m:
            m2 = re.match(r"^#\s+(HO-\d+)", title_line)
            if not m2:
                continue
            ho, title = m2.group(1), ""
        else:
            ho, title = m.group(1), m.group(2).strip()
        raw_rev = _strip(meta.get("Review", "none"))
        ids = [] if raw_rev.lower() in ("", "none") else re.findall(r"RV-\d+", raw_rev)
        result.append({
            "id": ho,
            "title": title,
            "status": _strip(meta.get("Status", "UNKNOWN")),
            "wp": meta.get("Work package", "none"),
            "branch": _strip(meta.get("Branch", "")),
            "commit": _strip(meta.get("Commit", "")),
            "parent": _strip(meta.get("Parent", "")),
            "reviews": ids,
            "responds": _strip(meta.get("Responds to", "none")) or "none",
            "supersedes": _strip(meta.get("Supersedes", "none")) or "none",
            "review_info": {r: reviews[r] for r in ids if r in reviews},
        })
    return result


def reviews_token(h) -> str:
    return ",".join(h["reviews"]) if h["reviews"] else "none"


def build_body(h, repo, server, ref_branch) -> str:
    branch = h["branch"] or ref_branch
    base = f"{server}/{repo}"
    sha = h["commit"]
    parent = h["parent"] or f"{sha}^"
    blob = f"{base}/blob/{branch}"
    ho = h["id"]
    rv = []
    for r in h["reviews"]:
        info = h["review_info"].get(r)
        link = f"{blob}/{REVIEWS}/{r}.md"
        if info:
            rv.append(f"{r} ({info['outcome']}, {info['date']}) [{r}.md]({link})")
        else:
            rv.append(f"{r} (file not found on disk) [{r}.md]({link})")
    reviews_line = "; ".join(rv) if rv else "none"
    lines = [
        f"<!-- coordination: {ho} status={h['status']} reviews={reviews_token(h)} commit={sha} -->",
        f"## Review requested: {ho} — {h['title']}",
        f"**Status:** `{h['status']}` (from the handoff file; automation never records a review)",
        f"**Work package:** {h['wp']}",
        f"**Commit:** `{sha}` — [commit]({base}/commit/{sha}) · "
        f"[diff vs parent]({base}/compare/{parent}...{sha}) · "
        f"[raw .diff]({base}/commit/{sha}.diff) · [checks]({base}/commit/{sha}/checks)",
        f"**Handoff:** [{HANDOFFS}/{ho}.md]({blob}/{HANDOFFS}/{ho}.md)",
        f"**Branch:** `{branch}`",
        f"**Responds to:** {h['responds']} · **Supersedes:** {h['supersedes']}",
        f"**Reviews on file:** {reviews_line}",
        "### How the owner starts the review",
        f'1. In the ChatGPT conversation, ask: "Review handoff {ho} at commit {sha} in '
        f'kreczmans-creator/repforge (branch {branch}) using docs/ai-coordination/REVIEW-TEMPLATE.md; '
        'return the outcome and the complete review file."',
        "2. Commit the returned file as docs/ai-coordination/reviews/RV-<next>.md on the branch "
        "and set the handoff's `Review:` line (or let Claude Code do it on its next session).",
        "3. The next push re-runs this automation and updates this issue.",
        "### Evidence for the reviewer",
        f"- Protocol: [AI-COORDINATION-PROTOCOL.md]({blob}/docs/ai-coordination/AI-COORDINATION-PROTOCOL.md)",
        f"- Review template: [REVIEW-TEMPLATE.md]({blob}/docs/ai-coordination/REVIEW-TEMPLATE.md)",
        f"- Delivery record: [docs/delivery-record/]({blob}/docs/delivery-record/)",
        f"- D05: [technical debt and risk register]({blob}/docs/wp0/D05-technical-debt-and-risk-register.md)",
        f"- D06: [work package roadmap]({blob}/docs/wp0/D06-work-package-roadmap.md)",
        f"- CURRENT-STATE: [CURRENT-STATE.md]({blob}/docs/ai-coordination/CURRENT-STATE.md)",
        "_Maintained by `.github/workflows/coordination.yml`. Closing this issue is bookkeeping, not acceptance._",
    ]
    return "\n".join(lines) + FOOTER


def build_comment(h, old, new_status, new_reviews, superseded_by=None) -> str:
    parts = []
    if old["status"] != new_status:
        parts.append(f"Status changed: {old['status']} → {new_status}")
        if new_status == "SUPERSEDED" and superseded_by:
            parts.append(f"Superseded by {superseded_by}")
    elif old["commit"] != h["commit"]:
        parts.append(f"Handoff commit changed: {old['commit'][:7]} → {h['commit'][:7]}")
    if old["reviews"] != new_reviews:
        if h["reviews"]:
            for r in h["reviews"]:
                info = h["review_info"].get(r)
                if info:
                    c = (info["commit"] or h["commit"])[:7]
                    parts.append(f"Review on file: {r} ({info['outcome']}) for commit {c}")
                else:
                    parts.append(f"Review listed in handoff: {r} (no review file found on disk)")
        else:
            parts.append("Reviews on file: none")
    return "\n\n".join(parts) + FOOTER


def fetch_issues(api, repo):
    issues, page = [], 1
    while True:
        batch = api.get(f"/repos/{repo}/issues?labels={LABEL}&state=all&per_page=100&page={page}")
        batch = batch or []
        issues.extend(batch)
        if len(batch) < 100:
            break
        page += 1
    mapped = {}
    for i in issues:
        if "pull_request" in i:
            continue
        m = TITLE_RE.match(i.get("title", ""))
        if m:
            mapped.setdefault(m.group(1), i)
    return mapped


def ensure_label(api, repo):
    try:
        api.post(f"/repos/{repo}/labels",
                 {"name": LABEL, "color": LABEL_COLOR, "description": LABEL_DESC})
    except ApiError as e:
        if e.status == 422 and "already_exists" in e.message:
            return
        raise


def sync(api, root: Path, repo: str, server: str, ref_branch: str,
         dry_run=False, offline=False, out=print) -> int:
    reviews = load_reviews(root)
    handoffs = load_handoffs(root, reviews)
    if not handoffs:
        out("no handoffs")
        return 0
    write = not dry_run
    if write:
        ensure_label(api, repo)
    elif not offline:
        out(f"[dry-run] would ensure label {LABEL}")
    existing = {} if (offline and dry_run) else fetch_issues(api, repo)

    def do(method, path, data, desc):
        if write:
            return getattr(api, method)(path, data)
        out(f"[dry-run] {desc}")
        return None

    superseder = {}
    for h in handoffs:
        m = re.search(r"HO-\d+", h["supersedes"])
        if m:
            superseder[m.group(0)] = h["id"]

    for h in handoffs:
        ho, status = h["id"], h["status"]
        title = f"[AI review] {ho} — {h['title']}"
        body = build_body(h, repo, server, ref_branch)
        issue = existing.get(ho)
        if issue is None:
            if status in CLOSING:
                out(f"skipped {ho} ({status}, no issue)")
                continue
            res = do("post", f"/repos/{repo}/issues",
                     {"title": title, "body": body, "labels": [LABEL]},
                     f"create issue for {ho}: {title}")
            out(f"created #{res['number']} for {ho}" if res else f"would create issue for {ho}")
            continue
        n = issue["number"]
        first = (issue.get("body") or "").splitlines()[:1]
        mm = MARKER_RE.match(first[0]) if first else None
        old = {"status": mm.group(2) if mm else "", "commit": mm.group(4) if mm else "",
               "reviews": ([] if not mm or mm.group(3) == "none" else mm.group(3).split(","))}
        differs = (not mm or old["status"] != status or old["commit"] != h["commit"]
                   or old["reviews"] != h["reviews"])
        is_open = issue.get("state") == "open"
        changed = False
        if differs:
            changed = True
            do("patch", f"/repos/{repo}/issues/{n}", {"title": title, "body": body},
               f"update body of #{n} ({ho})")
            do("post", f"/repos/{repo}/issues/{n}/comments",
               {"body": build_comment(h, old, status, h["reviews"], superseder.get(ho))},
               f"comment on #{n}")
        if status in CLOSING and is_open:
            changed = True
            do("patch", f"/repos/{repo}/issues/{n}",
               {"state": "closed", "state_reason": CLOSING[status]}, f"close #{n} ({CLOSING[status]})")
            out(f"closed #{n} for {ho}")
        elif status not in CLOSING and not is_open:
            changed = True
            do("patch", f"/repos/{repo}/issues/{n}", {"state": "open"}, f"reopen #{n}")
            out(f"reopened #{n} for {ho}")
        if differs:
            out(f"updated #{n} for {ho}")
        if not changed:
            out(f"unchanged #{n}")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", default=".")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--offline", action="store_true",
                    help="with --dry-run: skip reads too, assume no issues exist")
    args = ap.parse_args(argv)
    env = os.environ
    repo = env.get("GITHUB_REPOSITORY", "")
    token = env.get("GITHUB_TOKEN", "")
    if not repo:
        print("error: GITHUB_REPOSITORY is not set", file=sys.stderr)
        return 1
    if not token and not args.dry_run:
        print("error: GITHUB_TOKEN is not set; cannot sync review issues", file=sys.stderr)
        return 1
    api = GitHubApi(token, env.get("GITHUB_API_URL", "https://api.github.com"))
    try:
        return sync(api, Path(args.root), repo,
                    env.get("GITHUB_SERVER_URL", "https://github.com").rstrip("/"),
                    env.get("GITHUB_REF_NAME", ""), args.dry_run,
                    args.offline and args.dry_run)
    except ApiError as e:
        if e.status == 403:
            print(f"error: GitHub denied the request (rate limit or permissions): {e.message}",
                  file=sys.stderr)
        else:
            print(f"error: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
